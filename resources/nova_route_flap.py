def hold_route(hold, was_usable, now, last_good_ts, bad_streak, transitioning=False):
    """Оставить ли маршрут в PAC, хотя проба сейчас не проходит.

    `was_usable` — стоял ли он в PAC до этого такта. Удержание применимо только
    к падению: поднимать маршрут, который и так лежал, тут нечего.
    `transitioning` — маршрут сейчас запускается или восстанавливается; тогда
    неудачная проба ожидаема и о канале ничего не говорит.

    Возвращает True, если переворот делать рано.
    """
    if not was_usable:
        return False
    if not last_good_ts:
        # Удачной пробы не было ни разу — удерживать нечего, это не рябь.
        return False
    if (float(now) - float(last_good_ts)) >= hold.window_sec:
        return False
    if transitioning:
        return True
    return int(bad_streak) < hold.max_bad_probes


class FlapPenalty:
    """Маршрут, который повторно дёргается, убирается из PAC на время.

    Демпфер выше гасит рябь в секундах. Это — про другое: канал, который
    поднимается и падает раз за разом на протяжении часов. Замерено на логе
    пользователя, жаловавшегося на подтормаживания ПК (1.38, 4 ч 19 мин):

        30 падений маршрута WARP, 30 возвратов, и **ни одного**
        «Соединение восстановлено» — то есть восстановление не удалось ни разу.

    Каждая пара — два `INTERNET_OPTION_SETTINGS_CHANGED`, по которым все
    приложения WinINET перечитывают прокси. Никаким окном в секундах это не
    лечится: между падениями минуты. Лечится тем, что после нескольких падений
    подряд маршрут перестают возвращать, пока он не докажет, что держится.

    Цена ошибки несимметрична, и в этом весь расчёт. Держать WARP в PAC, когда
    он мёртв, — это зависшие вкладки: браузер соединяется с 1370 и ждёт. Не
    держать, когда он жив, — это трафик через Opera, которая рядом и работает.
    Поэтому сомнение трактуется в пользу Opera.

    Числа выбраны прогоном по его же отметкам времени, а не на глаз (255 минут,
    31 падение):

        порог  окно  скамейка   осталось   принудительно на Opera
          3    600 с   600 с    19 (-39%)          40 мин
          3    600 с   900 с    16 (-48%)          45 мин   <- взято
          3    600 с  1200 с    14 (-55%)          60 мин
          2    600 с   900 с    13 (-58%)          60 мин

    Взят средний. Порог 2 срабатывал бы и на здоровой машине, которой просто не
    повезло дважды; три падения за десять минут — это уже про канал.
    """

    __slots__ = ("threshold", "window_sec", "penalty_sec", "_downs", "_until")

    def __init__(self, threshold=3, window_sec=600.0, penalty_sec=900.0):
        self.threshold = int(threshold)
        self.window_sec = float(window_sec)
        self.penalty_sec = float(penalty_sec)
        self._downs = []
        self._until = 0.0

    def note_down(self, now):
        """Маршрут ушёл из PAC. Возвращает True, если это включило скамейку."""
        now = float(now)
        self._downs = [t for t in self._downs if now - t < self.window_sec]
        self._downs.append(now)
        if len(self._downs) >= self.threshold and now >= self._until:
            self._until = now + self.penalty_sec
            return True
        return False

    def benched(self, now):
        return float(now) < self._until

    def until(self):
        return self._until

    def forgive(self):
        """Маршрут доказал, что держится: счётчик и скамейка сбрасываются.

        Зовётся на настоящем успехе — восстановление подтвердилось или канал
        отработал чисто достаточно долго, — а не на каждой удачной пробе.
        Иначе один хороший ответ мёртвого канала снимал бы наказание.
        """
        self._downs = []
        self._until = 0.0


# Порог/окно/скамейка для WARP — см. замер в `FlapPenalty`.
