"""Удерживать ли маршрут, который только что перестал отвечать.

Каждая смена маршрута в PAC заканчивается `INTERNET_OPTION_SETTINGS_CHANGED` —
системным уведомлением, по которому **все** приложения WinINET перечитывают
настройки прокси и заново тянут PAC. Это не бесплатно и хорошо заметно: браузеры
подтормаживают. Поэтому переворот стоит делать только тогда, когда он настоящий.

Измерено на логе пользователя, 4 ч 19 мин, 1.38: 60 смен маршрута, из них
**21 провал длиной 3–5 секунд** — один-два такта watchdog. Каждый давал два
уведомления подряд.

Причина найдена прогоном вынутых из `nova.pyw` выражений: удержание снималось по
счётчику `warp_bad_proxy_streak < 3`, а вернуться хватало **одной** удачной
пробы. Три плохие пробы роняли маршрут, следующая хорошая поднимала — ровно те
3 секунды. Счётчик срабатывал раньше временного окна и делал его бесполезным.

Замер вариантов (всплеск из N плохих проб -> сколько переворотов дойдёт до
системы; и через сколько замечается настоящая смерть канала):

    порог  окно   N=3   N=4   N=5   смерть
      3    12 с    2     2     2     9 с    <- было
      5    12 с    0     2     2    12 с    <- стало
      -    20 с    0     0     0    21 с

Взят средний: он убирает все всплески, которые действительно встретились, ценой
трёх секунд, и не трогает временное окно — а это единственная страховка от того,
что счётчик окажется велик при другом такте опроса.
"""

__all__ = ["FlapHold", "WARP_HOLD", "OPERA_HOLD", "hold_route", "FlapPenalty", "WARP_PENALTY_SETTINGS"]


class FlapHold:
    """Насколько терпимы к пропаданию конкретного маршрута.

    `max_bad_probes` — сколько подряд неудачных проб ещё считаются рябью.
    `window_sec` — и сколько всего секунд с последней удачной пробы. Побеждает
    то, что кончится раньше; окно здесь главное, а счётчик — предохранитель на
    случай, если такт опроса когда-нибудь станет короче.
    """

    __slots__ = ("max_bad_probes", "window_sec")

    def __init__(self, max_bad_probes, window_sec):
        self.max_bad_probes = int(max_bad_probes)
        self.window_sec = float(window_sec)


